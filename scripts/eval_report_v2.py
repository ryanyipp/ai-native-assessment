r"""Refined scoring (v2): meaningful reference states and transitions, unmatched and duplicate states.

Reads only saved run records (FlowLens database) and frozen answer keys. Writes a Markdown report.
It does not claim website coverage: it counts which listed reference states/transitions were observed.

Usage:
  backend\.venv\Scripts\python scripts\eval_report_v2.py OUT_MD BATCH:ANSWER_KEY [BATCH:ANSWER_KEY ...]
"""

from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend" / "src"))

from flowlens.config import get_settings  # noqa: E402
from flowlens.storage.db import Store  # noqa: E402


def ref_of(st, refs):
    """First reference state this recorded state matches. Message checks use the state summary,
    which carries the first alert or status message."""
    head, _, msg = st.summary.partition(" — ")
    for r in refs:
        if st.route != r["route"] or not head.startswith(r["heading"]):
            continue
        if r.get("needs_alert") and not msg:
            continue
        if (r.get("no_alert") or r.get("no_status")) and msg:
            continue
        if r.get("status_contains") and r["status_contains"] not in msg.lower():
            continue
        return r["id"]
    return None


def defect_hit(f, k) -> bool:
    if f.requirement_ref != k["requirement"]:
        return False
    if k["predicate"] == "requirement_only":
        return True
    v = (f.inputs or {}).get(k["field"] or "", "")
    if k["predicate"] == "date_lt":
        return bool(v) and v < k["value"]
    if k["predicate"] == "int_gt":
        try:
            return int(v) > k["value"]
        except ValueError:
            return False
    return False


def score(rec, d, key):
    build = rec["build"]
    refs = key["reference_states"]
    required = [r["id"] for r in refs if build not in r.get("optional_on", [])]
    mapping = {s.id: ref_of(s, refs) for s in d.states}
    seen = [m for m in mapping.values() if m]
    matched = set(seen)
    dup = sum(seen.count(r) - 1 for r in matched)
    unmatched = [s.summary for s in d.states if mapping[s.id] is None]
    trans = {(mapping.get(t.source_state_id), mapping.get(t.target_state_id)) for t in d.transitions}
    ref_tr = [tuple(x) for x in key["reference_transitions"]]
    tr_hit = [x for x in ref_tr if x in trans]
    cand = [f for f in d.findings if f.kind != "persistence_check"]
    conf = [f for f in cand if f.verification_status == "confirmed"]
    defects = [k for k in key["known_defects"] if build in k["builds"]]
    found = [k["id"] for k in defects if any(defect_hit(f, k) for f in conf)]
    false = [f for f in conf if not any(defect_hit(f, k) for k in defects)]
    run = d.run
    return {
        **{k: rec[k] for k in ("condition", "build", "rep", "run_id")}, "status": run.status.value,
        "ref_states": f"{len(matched & set(required))}/{len(required)}", "ref_states_n": len(matched & set(required)),
        "ref_transitions": f"{len(tr_hit)}/{len(ref_tr)}", "ref_transitions_n": len(tr_hit),
        "missing_states": [r for r in required if r not in matched],
        "states": len(d.states), "duplicates": dup, "unmatched": len(unmatched), "unmatched_examples": unmatched[:4],
        "found": found, "missed": [k["id"] for k in defects if k["id"] not in found],
        "false_confirmations": [f"{f.requirement_ref}: {f.description[:70]}" for f in false],
        "confirmed": len(conf), "inconclusive": sum(f.verification_status == "inconclusive" for f in cand),
        "unfinished": sum(t.status in ("unfinished", "blocked", "failed") for t in d.tasks),
        "skipped": sum(t.status == "skipped" for t in d.tasks),
        "elapsed_s": round((run.finished_at - run.created_at).total_seconds(), 1) if run.finished_at else None,
        "calls": run.usage.model_calls, "tokens": run.usage.total_tokens, "cost": run.usage.reported_cost_usd,
        "conf_detail": [{"req": f.requirement_ref, "inputs": f.inputs, "by": f.verified_by,
                         "independence": f.verification_independence} for f in conf],
    }


def mm(xs, nd=0):
    xs = [x for x in xs if x is not None]
    return f"{statistics.mean(xs):.{nd}f} ({min(xs):.{nd}f}–{max(xs):.{nd}f})" if xs else "–"


def main(out_md: str, pairs: list[str]) -> None:
    store = Store(get_settings().database_path)
    L = ["# Evaluation, part 2: refined scoring and a held-out app", "",
         "Generated by `scripts/eval_report_v2.py` from saved run records and frozen answer keys. "
         "Reference states and transitions are a short, listed set of meaningful pages and moves, not the whole "
         "website. **Unmatched** states fit no reference entry, and **duplicates** are extra recorded states that "
         "map to an already-matched reference (for example, filled-field variants).", ""]
    for pair in pairs:
        batch, key_path = pair.split(":", 1)
        key = json.loads((ROOT / key_path).read_text("utf-8"))
        recs = [json.loads(x) for x in (ROOT / "evaluation" / "results" / batch / "runs.jsonl").read_text("utf-8").splitlines() if x.strip()]
        scores = [score(r, store.detail(r["run_id"]), key) for r in recs]
        (ROOT / "evaluation" / "results" / batch / f"scores_v2_{Path(key_path).parent.name}.json").write_text(
            json.dumps(scores, indent=2, default=str), "utf-8")
        L += [f"## `{batch}` scored with `{key_path}`", "",
              "| Condition | Build | Rep | Run | Status | Ref states | Ref transitions | States | Duplicates | Unmatched | "
              "Defects found | Missed | False conf. | Inconclusive | Unfinished | Skipped | s | Calls | Tokens | US$ |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for s in scores:
            L.append(f"| {s['condition']} | {s['build']} | {s['rep']} | `{s['run_id']}` | {s['status']} | {s['ref_states']} | "
                     f"{s['ref_transitions']} | {s['states']} | {s['duplicates']} | {s['unmatched']} | "
                     f"{', '.join(s['found']) or '–'} | {', '.join(s['missed']) or '–'} | {len(s['false_confirmations'])} | "
                     f"{s['inconclusive']} | {s['unfinished']} | {s['skipped']} | {s['elapsed_s']} | {s['calls']} | "
                     f"{s['tokens']} | {s['cost']:.4f} |")
        L += ["", "Summary, mean (min–max):", "",
              "| Condition | Build | Runs | Ref states | Ref transitions | Duplicates | Unmatched | Defects found | "
              "False conf. | Unfinished | s | Calls | US$ |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for c in dict.fromkeys(s["condition"] for s in scores):
            for b in ("broken", "corrected"):
                g = [s for s in scores if s["condition"] == c and s["build"] == b]
                if not g:
                    continue
                known = len(g[0]["found"]) + len(g[0]["missed"])
                fd = (f"{sum(len(s['found']) for s in g)}/{known * len(g)}") if known else "n/a"
                L.append(f"| {c} | {b} | {len(g)} | {mm([s['ref_states_n'] for s in g], 1)} | "
                         f"{mm([s['ref_transitions_n'] for s in g], 1)} | {mm([s['duplicates'] for s in g])} | "
                         f"{mm([s['unmatched'] for s in g])} | {fd} | {sum(len(s['false_confirmations']) for s in g)} | "
                         f"{mm([s['unfinished'] for s in g])} | {mm([s['elapsed_s'] for s in g])} | "
                         f"{mm([s['calls'] for s in g])} | {mm([s['cost'] for s in g], 4)} |")
        fc = [(s["run_id"], x) for s in scores for x in s["false_confirmations"]]
        L += ["", "False confirmations: " + ("; ".join(f"`{r}` {x}" for r, x in fc) if fc else "none") + ".",
              "Confirmed findings: " + "; ".join(f"`{s['run_id']}` {c['req']} {json.dumps(c['inputs'], ensure_ascii=False)} "
                                                  f"({c['independence']})" for s in scores for c in s["conf_detail"]) + ".",
              f"Batch total: {len(scores)} runs, {sum(s['calls'] for s in scores)} calls, "
              f"{sum(s['tokens'] for s in scores):,} tokens, US${sum(s['cost'] for s in scores):.4f}.", ""]
    (ROOT / out_md).write_text("\n".join(L) + "\n", "utf-8")
    print("wrote", out_md)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2:])
